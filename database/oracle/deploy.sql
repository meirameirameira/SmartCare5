-- Mesmo DDL de HEALTH_ALERT_AUDIT em 01_ddl_tabelas.sql.
DECLARE
    v_existe PLS_INTEGER;
BEGIN
    SELECT COUNT(*) INTO v_existe FROM user_tables WHERE table_name = 'HEALTH_ALERT_AUDIT';
    IF v_existe = 0 THEN
        EXECUTE IMMEDIATE q'[
            CREATE TABLE health_alert_audit (
                id               NUMBER(19)     GENERATED BY DEFAULT AS IDENTITY,
                alert_id         NUMBER(19)     NOT NULL,
                patient_id       NUMBER(19)     NOT NULL,
                operation        VARCHAR2(12)   NOT NULL,
                alert_type       VARCHAR2(20),
                metric           VARCHAR2(60),
                title            VARCHAR2(160),
                old_acknowledged NUMBER(1),
                new_acknowledged NUMBER(1),
                changed_at       TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
                db_user          VARCHAR2(128)  DEFAULT USER NOT NULL,
                client_module    VARCHAR2(64),
                CONSTRAINT pk_health_alert_audit PRIMARY KEY (id),
                CONSTRAINT ck_alert_audit_op     CHECK (operation IN ('CRIACAO', 'RECONHECIDO', 'REABERTO',
                                                                      'ALTERACAO', 'EXCLUSAO'))
            )]';
        EXECUTE IMMEDIATE 'CREATE INDEX idx_alert_audit_alert   ON health_alert_audit (alert_id, changed_at)';
        EXECUTE IMMEDIATE 'CREATE INDEX idx_alert_audit_patient ON health_alert_audit (patient_id, changed_at)';
        DBMS_OUTPUT.PUT_LINE('HEALTH_ALERT_AUDIT criada.');
    ELSE
        DBMS_OUTPUT.PUT_LINE('HEALTH_ALERT_AUDIT ja existe.');
    END IF;
END;
