PROMPT == 3/4 Triggers e limpeza das rotinas avulsas da Fase 6
@@07_triggers.sql

DECLARE
    e_inexistente EXCEPTION;
    PRAGMA EXCEPTION_INIT(e_inexistente, -4043);
BEGIN
    FOR r IN (SELECT object_type, object_name
                FROM user_objects
               WHERE object_type IN ('FUNCTION', 'PROCEDURE')
                 AND object_name IN ('PRC_CONSOLIDAR_RELATORIO', 'PRC_REGISTRAR_LEITURA',
                                     'PRC_REGISTRAR_ALERTAS_LEITURA', 'PRC_LOG_EXECUCAO',
                                     'FN_FORMATAR_RESUMO_PACIENTE', 'FN_FORMATAR_LEITURA',
                                     'FN_ROTULO_NIVEL', 'FN_TEMPO_NA_FAIXA',
                                     'FN_CALCULAR_SCORE_SAUDE', 'FN_CLASSIFICAR_SINAL')) LOOP
        BEGIN
            EXECUTE IMMEDIATE 'DROP ' || r.object_type || ' ' || r.object_name;
            DBMS_OUTPUT.PUT_LINE('Removida rotina avulsa ' || r.object_name);
        EXCEPTION
            WHEN e_inexistente THEN NULL;
        END;
    END LOOP;
END;
/

